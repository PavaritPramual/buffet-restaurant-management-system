// Isolated runtime only; no shared database, no HTTP mocks and no recorded credentials.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const web = process.env.FINAL_WEB_URL, api = process.env.FINAL_API_URL
assert.equal(process.env.FINAL_ENVIRONMENT, 'local-h2')
assert.equal(process.env.FINAL_ALLOW_TEST_DATA, 'true')
assert(['127.0.0.1', 'localhost'].includes(new URL(api).hostname))
const output = path.resolve(process.env.FINAL_EVIDENCE_DIR || 'output/playwright', 'menu-stock')
const results = [], contexts = {}, startedAt = new Date().toISOString()
const pass = (scenario, detail) => results.push({ scenario, result: 'PASS', detail })
async function main() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    for (const [name, width] of Object.entries({ manager:1280, staff:768, kitchen:768, customer:360, anonymous:360 })) {
      contexts[name] = await browser.newContext({ viewport: { width, height:1000 } })
      contexts[name].page = await contexts[name].newPage()
    }
    async function call(role, method, endpoint, data, expected = 200) {
      const response = await contexts[role].request[method](api + endpoint, { headers: { Origin: new URL(web).origin }, ...(data === undefined ? {} : { data }) })
      assert.equal(response.status(), expected, `${method} ${endpoint}`)
      return expected === 204 ? null : response.json()
    }
    async function shot(role, name) {
      const page = contexts[role].page
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), page.viewportSize().width, `${role} horizontal overflow`)
      await page.screenshot({ path:path.join(output,name), fullPage:true, mask:[page.locator('.staff-session-qr-card')] })
    }
    for (const name of ['manager','staff','kitchen']) {
      const page = contexts[name].page
      await page.goto(web + '/admin')
      await page.getByLabel('ชื่อผู้ใช้',{exact:true}).fill(process.env[`FINAL_${name.toUpperCase()}_USERNAME`])
      await page.getByLabel('รหัสผ่าน',{exact:true}).fill(process.env[`FINAL_${name.toUpperCase()}_PASSWORD`])
      await page.getByRole('button',{name:'เข้าสู่ระบบ',exact:true}).click()
      await page.waitForURL(`**${name === 'staff' ? '/staff/tables' : name === 'kitchen' ? '/kitchen' : '/admin/stock'}`)
    }
    const stock = await call('manager','post','/stock/items',{ sku:'PORK-RECIPE',name:'หมูสไลซ์',unit:'กิโลกรัม',lowStockThreshold:0.1,openingTargetStock:1 },201)
    await call('manager','post',`/stock/${stock.id}/in`,{quantity:0.15,reason:'รับวัตถุดิบก่อนเปิดร้าน'})
    const pack=await call('manager','post','/buffet-packages',{name:'บุฟเฟต์มาตรฐาน',price:299,active:true},201)
    const soup=await call('manager','post','/soups',{name:'น้ำซุปใส',active:true},201)
    const table=await call('manager','post','/tables',{tableNumber:'S01',capacity:4,status:'AVAILABLE'},201)
    const category=await call('manager','post','/menu-categories',{name:'เนื้อสัตว์'},201)
    const manager=contexts.manager.page
    await manager.goto(web+'/admin/menu')
    await manager.getByLabel('ชื่อเมนู',{exact:true}).fill('หมูสไลซ์หนึ่งจาน')
    await manager.getByLabel('หมวดหมู่',{exact:true}).selectOption(String(category.id))
    await manager.getByLabel(pack.name,{exact:true}).check()
    await manager.getByRole('combobox',{name:/^การหักสต๊อก/}).selectOption('on')
    await manager.getByRole('button',{name:'เพิ่มวัตถุดิบ',exact:true}).click()
    await manager.getByRole('combobox',{name:/^วัตถุดิบ 1/}).selectOption(String(stock.id))
    await manager.getByLabel('ปริมาณต่อเสิร์ฟ 1 (กิโลกรัม)',{exact:true}).fill('0.100')
    await shot('manager','manager-recipe-1280.png')
    const saved=manager.waitForResponse(response=>response.url().endsWith('/menu-items')&&response.request().method()==='POST')
    await manager.getByRole('button',{name:'บันทึกเมนู',exact:true}).click()
    const created=await saved; assert.equal(created.status(),201); const menu=await created.json()
    await manager.getByText('บันทึกเมนูแล้ว',{exact:true}).waitFor()
    const recipe=await call('manager','get',`/menu-items/${menu.id}/stock-usage`)
    assert.equal(recipe.stockUsage[0].quantityPerServing,0.1)
    await call('kitchen','get',`/menu-items/${menu.id}/stock-usage`,undefined,403)
    await call('anonymous','get',`/menu-items/${menu.id}/stock-usage`,undefined,401)
    pass('Manager saves recipe through shared UI; recipe read is Manager-only',{menuId:menu.id,stockItemId:stock.id})
    const session=await call('staff','post','/dining-sessions',{tableId:table.id,packageId:pack.id,soupId:soup.id,adultCount:1,childCount:0},201)
    const customer=contexts.customer.page
    await customer.goto(web+'/customer/qr#token='+session.sessionToken)
    await customer.getByRole('button',{name:'เพิ่ม '+menu.name,exact:true}).click()
    await customer.getByRole('button',{name:'เพิ่ม '+menu.name,exact:true}).click()
    await customer.getByRole('button',{name:'ยืนยันการสั่ง',exact:true}).click()
    await customer.getByRole('dialog').getByRole('button',{name:'ยืนยัน',exact:true}).click()
    await customer.locator('.order-card').waitFor()
    assert.equal(new URL(customer.url()).hash,'')
    const order=(await call('customer','get',`/dining-sessions/${session.sessionId}/orders`))[0]
    assert.equal(order.items[0].quantity,2)
    await shot('customer','customer-order-360.png')
    const kitchen=contexts.kitchen.page
    await kitchen.reload()
    const ticket=kitchen.locator('.order-board-card').filter({hasText:'ออเดอร์ #'+order.orderId})
    const failed=kitchen.waitForResponse(response=>response.url().endsWith(`/orders/${order.orderId}/status`))
    await ticket.getByRole('button',{name:'เริ่มเตรียมอาหาร',exact:true}).click()
    assert.equal((await failed).status(),409)
    await kitchen.getByRole('alert').filter({hasText:'หมูสไลซ์'}).waitFor()
    await shot('kitchen','kitchen-insufficient-768.png')
    assert.equal((await call('manager','get','/stock'))[0].quantity,0.15)
    assert.equal((await call('customer','get',`/dining-sessions/${session.sessionId}/orders`))[0].status,'RECEIVED')
    pass('Insufficient stock leaves both stock and order unchanged',{status:409})
    await call('manager','post',`/stock/${stock.id}/in`,{quantity:0.35,reason:'เติมวัตถุดิบก่อนเริ่มทำ'})
    await call('manager','put',`/menu-items/${menu.id}`,{categoryId:category.id,name:menu.name,available:true,packageIds:[pack.id],automaticStockDeduction:true,stockUsage:[{stockItemId:stock.id,quantityPerServing:0.2}]})
    await ticket.getByRole('button',{name:'เริ่มเตรียมอาหาร',exact:true}).click()
    await ticket.getByRole('button',{name:'พร้อมเสิร์ฟแล้ว',exact:true}).waitFor()
    await shot('kitchen','kitchen-preparing-768.png')
    assert.equal((await call('manager','get','/stock'))[0].quantity,0.3)
    await call('kitchen','patch',`/orders/${order.orderId}/status`,{status:'PREPARING'},400)
    const movements=await call('manager','get','/stock/transactions')
    const consumption=movements.filter(entry=>entry.transactionType==='CONSUMPTION')
    assert.equal(consumption.length,1); assert.equal(consumption[0].quantityDelta,-0.2); assert.equal(consumption[0].orderId,order.orderId)
    pass('Frozen recipe survives edit; kitchen consumes once',{consumed:0.2,balance:0.3,orderId:order.orderId})
    await ticket.getByRole('button',{name:'พร้อมเสิร์ฟแล้ว',exact:true}).click()
    await ticket.waitFor({state:'hidden'})
    await call('staff','patch',`/orders/${order.orderId}/status`,{status:'SERVED'})
    await call('customer','post',`/dining-sessions/${session.sessionId}/bill-request`)
    const payment=await call('staff','post','/payments',{sessionId:session.sessionId,paymentMethod:'CASH'},201)
    assert.equal(payment.amount,299)
    await call('staff','post',`/dining-sessions/${session.sessionId}/close`)
    await call('customer','get',`/dining-sessions/${session.sessionId}/orders`,undefined,401)
    await manager.goto(web+'/admin/stock')
    await manager.getByText('ใช้ทำอาหาร',{exact:true}).waitFor()
    await shot('manager','manager-consumption-history-1280.png')
    pass('Stock audit UI and Payment/close remain consistent',{paymentAmount:payment.amount,stockBalance:0.3})
    await manager.goto(new URL(api).origin+'/swagger-ui/index.html')
    await manager.getByText('Menu Item Management',{exact:true}).first().waitFor()
    const spec=await (await contexts.manager.request.get(new URL(api).origin+'/v3/api-docs')).json()
    assert(spec.paths['/api/v1/menu-items/{id}/stock-usage'].get)
    assert(spec.components.schemas.MenuItemRequest.properties.stockUsage)
    assert(spec.paths['/api/v1/orders/{id}/status'].patch.responses['409'])
    await shot('manager','swagger-stock-contract-1280.png')
    pass('Swagger UI loads; new recipe and consumption contracts present','HTTP feature calls above exercise changed endpoints with real cookies')
  } catch (error) {
    const manager = contexts.manager?.page
    if (manager && new URL(manager.url()).pathname === '/admin/menu') {
      await manager.screenshot({path:path.join(output,'failure-manager-menu.png'),fullPage:true})
      await fs.writeFile(path.join(output,'failure-manager-menu.txt'),await manager.locator('main').innerText())
    }
    throw error
  } finally { await browser.close() }
  await fs.writeFile(path.join(output,'results.json'),JSON.stringify({sourceCommit:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),sourceState:execFileSync('git',['status','--porcelain'],{encoding:'utf8'}).trim() ? 'working tree; pair with PR diff' : 'clean',runnerCommit:'same PR',startedAt,finishedAt:new Date().toISOString(),environment:'fresh isolated H2 / real session and database providers',httpMocks:false,publicAcceptance:false,results},null,2)+'\n')
  console.log(`PASS ${results.length} menu-stock browser scenarios`)
}
main().catch(error=>{console.error(error.message);process.exitCode=1})
